export type Reply =
  | string
  | { text: string; when: (c: ChatCtx, m: Mem) => boolean };

export type Intent = {
  id: string;
  test: RegExp[];
  priority: number;
  replies: Reply[];
  gentle?: string[]; // вариант для тяжёлого разговора (вместо шуток и болтовни)
  heavy?: boolean; // тема тяжёлая: на ближайшие ходы шутки отключаются
  chips?: ChipDef[];
  action?: ChatAction;
  pose?: Pose;
  addon?: boolean;
};

const say = (label: string, text = label): ChipDef => ({
  label,
  action: { type: "say", text },
});
const go = (
  label: string,
  action: ChatAction,
  extra: Partial<ChipDef> = {},
): ChipDef => ({ label, action, ...extra });

